/**
 * Configure standard column widths for an array of objects
 */
function calculateAutoWidth(jsonArray) {
    if (!jsonArray || jsonArray.length === 0) return [];
    const keys = Object.keys(jsonArray[0]);
    return keys.map(key => {
        let maxLen = key.length;
        for (let i = 0; i < Math.min(jsonArray.length, 50); i++) {
            const val = jsonArray[i][key];
            if (val !== undefined && val !== null) {
                const str = String(val);
                if (str.length > maxLen) maxLen = str.length;
            }
        }
        return { wch: Math.min(Math.max(maxLen + 4, 12), 48) };
    });
}

